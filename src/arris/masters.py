# Lowercase: x-height nine rows, ascenders four rows above it (thirteen to
# the baseline, one above the capitals), descenders three below. Each master
# is padded to sixteen rows: four ascender rows, nine x-height rows, three
# descender rows; the baseline sits under row 12.
ASC, XH, DESC = 4, 9, 3


def lc(x, asc=(), desc=()):
    w = len(x[0])
    blank = '.' * w
    asc = list(asc)
    desc = list(desc)
    return [blank] * (ASC - len(asc)) + asc + list(x) + desc + [blank] * (DESC - len(desc))


